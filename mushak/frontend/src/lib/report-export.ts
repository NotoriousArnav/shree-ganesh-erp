import { buildXlsx, buildZip, rowsToCsv, type ExportCell, type ExportSheet } from "@ganesh/shared";

import { dateTime, movementLabels } from "./format";
import { formatBound, formatFluent } from "./range";
import type { ShopReportData } from "./types";

/**
 * Client-side report exports.
 *
 * The report is already loaded in the browser, so both formats are generated
 * from that snapshot. The XLSX and ZIP writers live in `@ganesh/shared` so
 * Lokkhi can export invoices with the same package structure.
 */

function shopAddress(data: ShopReportData) {
  const address = data.merchant?.address;
  if (!address) return "No address on file";

  return (
    [address.line1, address.line2, address.city, address.state, address.pincode]
      .filter(Boolean)
      .join(", ") || "No address on file"
  );
}

function shopContact(data: ShopReportData) {
  const merchant = data.merchant;
  const parts = [
    merchant?.phone ? `Phone ${merchant.phone}` : null,
    merchant?.gstin ? `GSTIN ${merchant.gstin}` : null,
  ].filter(Boolean);

  return parts.length > 0 ? parts.join(" · ") : "No contact details on file";
}

function reportRows(data: ShopReportData): ExportCell[][] {
  return [
    ["Field", "Value"],
    ["Report", "Mushak shop report"],
    ["Shop", data.merchant?.name ?? "Unknown shop"],
    ["Address", shopAddress(data)],
    ["Contact", shopContact(data)],
    ["Generated at", dateTime(data.generatedAt)],
    ["Generated by", data.generatedBy],
    ["From", `${formatFluent(data.range.from)} (${formatBound(data.range.from)})`],
    ["To", `${formatFluent(data.range.to)} (${formatBound(data.range.to)})`],
    ["Active products", data.counts.activeProducts],
    ["Archived products", data.counts.products - data.counts.activeProducts],
    ["Categories", data.counts.categories],
    ["Movements in range", data.period.movements],
    ["Quantity in", data.period.inQty],
    ["Quantity out", data.period.outQty],
    ["Stock value at cost", data.value.cost],
    ["Stock value at retail", data.value.retail],
    ["Potential margin", data.value.margin],
    ["Currency", data.value.currency],
    ["Healthy products", data.stockHealth.healthy],
    ["Low-stock products", data.stockHealth.low],
    ["Out-of-stock products", data.stockHealth.outOfStock],
    [
      "Movements included",
      data.truncated
        ? `${data.movements.length} of ${data.movementTotal} (most recent only)`
        : data.movements.length,
    ],
    [
      "Export note",
      data.truncated
        ? `The movement sheet is capped at ${data.movements.length} rows to match the report. Narrow the range for the full history.`
        : "All movements in the range are included.",
    ],
  ];
}

export function reportSheets(data: ShopReportData): ExportSheet[] {
  const currency = data.value.currency;

  return [
    {
      name: "Summary",
      rows: reportRows(data),
      headerRows: [0],
    },
    {
      name: "Categories",
      rows: [
        ["Category", "Products", `Cost (${currency})`, `Retail (${currency})`],
        ...data.categories.map((row): ExportCell[] => [
          row.name,
          row.products,
          row.cost,
          row.retail,
        ]),
      ],
      headerRows: [0],
    },
    {
      name: "Needs reordering",
      rows: [
        ["Product", "Stock", "Reorder at", "Unit"],
        ...data.lowStock.map((row): ExportCell[] => [
          row.name,
          row.stockQty,
          row.reorderLevel,
          row.unit,
        ]),
      ],
      headerRows: [0],
    },
    {
      name: "Out of stock",
      rows: [
        ["Product", "Stock", "Unit", "Last updated"],
        ...data.outOfStock.map((row): ExportCell[] => [
          row.name,
          row.stockQty,
          row.unit,
          dateTime(row.updatedAt),
        ]),
      ],
      headerRows: [0],
    },
    {
      name: "Top stock value",
      rows: [
        ["Product", "On hand", "Unit", `Cost (${currency})`, `Retail (${currency})`],
        ...data.topValue.map((row): ExportCell[] => [
          row.name,
          row.stockQty,
          row.unit,
          row.cost,
          row.retail,
        ]),
      ],
      headerRows: [0],
    },
    {
      name: "Movements",
      rows: [
        ["When", "Product", "Type", "Quantity", "Unit", "Unit cost", "Note", "Recorded at (ISO)"],
        ...data.movements.map((row): ExportCell[] => [
          dateTime(row.createdAt),
          row.productName,
          movementLabels[row.type] ?? row.type,
          row.quantity,
          row.unit,
          row.unitCost,
          row.note ?? "",
          row.createdAt,
        ]),
      ],
      headerRows: [0],
    },
  ];
}

/** One UTF-8 CSV per report section, ready to be zipped. */
export function reportCsvFiles(data: ShopReportData) {
  const files = [
    "01-summary.csv",
    "02-categories.csv",
    "03-needs-reordering.csv",
    "04-out-of-stock.csv",
    "05-top-stock-value.csv",
    "06-movements.csv",
  ];

  return reportSheets(data).map((sheet, index) => ({
    name: files[index] ?? `${index + 1}-${sheet.name}.csv`,
    content: rowsToCsv(sheet.rows),
  }));
}

/** Builds a ZIP containing one CSV per report section. */
export function buildCsvZip(data: ShopReportData): Uint8Array {
  return buildZip(
    reportCsvFiles(data).map((file) => ({
      name: file.name,
      bytes: new TextEncoder().encode(file.content),
    })),
  );
}

function download(filename: string, blob: Blob) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function rangePart(epoch: number) {
  const date = new Date(epoch * 1000);
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

export function reportFilename(data: ShopReportData, extension: string) {
  return `mushak-report-${rangePart(data.range.from)}-to-${rangePart(data.range.to)}.${extension}`;
}

function binaryBlob(bytes: Uint8Array, type: string) {
  const buffer = new ArrayBuffer(bytes.byteLength);
  new Uint8Array(buffer).set(bytes);
  return new Blob([buffer], { type });
}

/** Downloads a ZIP with one CSV per report section. */
export function downloadReportCsv(data: ShopReportData) {
  download(
    reportFilename(data, "csv.zip"),
    binaryBlob(buildCsvZip(data), "application/zip"),
  );
}

export function downloadReportXlsx(data: ShopReportData) {
  download(
    reportFilename(data, "xlsx"),
    binaryBlob(
      buildXlsx(reportSheets(data)),
      "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    ),
  );
}

/** Downloads the report response as-is, pretty-printed for reading or scripts. */
export function downloadReportJson(data: ShopReportData) {
  download(
    reportFilename(data, "json"),
    new Blob([`${JSON.stringify(data, null, 2)}\n`], {
      type: "application/json;charset=utf-8",
    }),
  );
}
